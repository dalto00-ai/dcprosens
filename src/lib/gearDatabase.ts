// src/lib/gearDatabase.ts
// Extended gear database: keyboards, headsets, monitors, mousepads

export interface Keyboard {
    id: string;
    name: string;
    brand: string;
    switch: string;
    form: string; // TKL, 60%, 65%, Full
    connectivity: 'Wired' | 'Wireless' | 'Both';
    price: string;
    proUsage: string[];
    features: string[];
    affiliateLink: string;
    rating: number;
    badge?: string;
    image?: string;
}

export interface Headset {
    id: string;
    name: string;
    brand: string;
    type: 'Wired' | 'Wireless';
    driver: string; // driver size mm
    frequency: string; // Hz range
    microphone: boolean;
    surround: boolean;
    weight: number; // grams
    price: string;
    proUsage: string[];
    affiliateLink: string;
    rating: number;
    badge?: string;
    image?: string;
}

export interface Monitor {
    id: string;
    name: string;
    brand: string;
    size: number; // inches
    resolution: string;
    refreshRate: number; // Hz
    panelType: 'TN' | 'IPS' | 'VA' | 'OLED';
    responseTime: string; // ms
    price: string;
    proUsage: string[];
    affiliateLink: string;
    rating: number;
    badge?: string;
    image?: string;
}

export interface Mousepad {
    id: string;
    name: string;
    brand: string;
    size: string; // S / M / L / XL / Extended
    dimensions: string; // WxH mm
    thickness: string; // mm
    surface: 'Cloth' | 'Hard' | 'Hybrid';
    price: string;
    proUsage: string[];
    affiliateLink: string;
    rating: number;
    badge?: string;
    bestFor: string; // low / mid / high sens
    image?: string;
}

